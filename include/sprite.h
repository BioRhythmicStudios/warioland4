    /* 0x0E */ u16 affinePB;
    /* 0x10 */ u16 affinePC;
    /* 0x12 */ u16 affinePD;
    /* 0x14 */ u16 animationTimer;
    /* 0x16 */ u8 currentAnimationFrame;
    /* 0x17 */ u8 globalID;
    /* 0x18 */ u8 roomSlot;
    /* 0x19 */ u8 gfxSlot;
    /* 0x1A */ u8 drawPriority;
    /* 0x1B */ u8 palette;
    /* 0x1C */ u8 pose;
    /* 0x1D */ u8 health;
    /* 0x1E */ u8 warioCollision;
    /* 0x1F */ u8 disableWarioCollisionTimer;
    /* 0x20 */ u8 drawDistanceDown;
    /* 0x21 */ u8 drawDistanceUp;
    /* 0x22 */ u8 drawDistanceLeftRight;
    /* 0x23 */ u8 hitboxExtentUp;
    /* 0x24 */ u8 hitboxExtentDown;
