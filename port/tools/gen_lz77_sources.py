#!/usr/bin/env python3
"""List the LZ77 streams that the game passes to LZ77UnCompVram, for wl4 --test-bios.

usage: python port/tools/gen_lz77_sources.py   (from the repo root, after gen_symbols.py)

Reads the calls in src/ and the addresses in port/generated/gba_symbols.s, and writes
port/generated/lz77_sources.c.
"""
import pathlib
import re
import sys

OUT = pathlib.Path('port/generated/lz77_sources.c')
CALL = re.compile(r'LZ77UnCompVram\(\s*(?:\(\s*const\s+u32\s*\*\s*\)\s*)?([A-Za-z_]\w*)\s*,')
# Sources passed through a local variable rather than by name.
INDIRECT = {
    'graphicsSource': ['sFileSelectInterfaceTiles'],  # file_select.c
    'src': [],  # init_helpers.c's LZ77UnCompVramWrapper, which no C code calls
}


def main():
    addresses = {}
    text = pathlib.Path('port/generated/gba_symbols.s').read_text()
    for name, addr in re.findall(r'\.set (\w+), (0x[0-9A-Fa-f]+)', text):
        addresses[name] = int(addr, 16)

    names = set()
    for path in sorted(pathlib.Path('src').rglob('*.c')):
        for name in CALL.findall(path.read_text(errors='replace')):
            names.update(INDIRECT.get(name, [name]))
    missing = sorted(n for n in names if n not in addresses)
    if missing:
        sys.exit('no GBA address for: ' + ' '.join(missing))

    lines = ['// Generated by port/tools/gen_lz77_sources.py. Do not edit.\n',
             '#include "port/bios.h"\n\n',
             'const struct PortLz77Source gLz77Sources[] = {\n']
    lines += ['    { "%s", 0x%08X },\n' % (n, addresses[n]) for n in sorted(names, key=lambda n: addresses[n])]
    lines.append('};\n\nconst unsigned int gLz77SourceCount = sizeof(gLz77Sources) / sizeof(gLz77Sources[0]);\n')
    OUT.write_bytes(''.join(lines).encode())
    print('%d LZ77 sources' % len(names))


if __name__ == '__main__':
    main()
