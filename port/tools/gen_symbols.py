#!/usr/bin/env python3
"""Generate the PC port's links to the GBA symbol table.

usage: python port/tools/gen_symbols.py --elf build/playtest/warioland4_us_playtest.elf
                                        --lib build_pc/libwl4_game.a [--nm llvm-nm]

The ELF must keep every symbol at its address in the base ROM: use the playtest build
(tools/build_playtest_rom.py), not build/us, where the unmatched functions move the code
and data that follow them. The library is the PC build of the game code.

Writes, in port/generated/:
- gba_symbols.s: every data symbol as an absolute symbol at its GBA address, so that
  game code reads ROM data from the loaded ROM and RAM variables from the mapped RAM.
  The linker constants (gNumMusicPlayers, gMaxLines) come out the same way.
- gba_functions.c: the dispatch table from the GBA address of each function to its
  native function (or stub), for function pointers that the game keeps in GBA memory.
- gba_stubs.c: weak stubs for the GBA functions the game calls that have no native
  version yet (the asm functions). Each one reports its name and address and stops;
  a platform definition replaces it.
"""
import argparse
import pathlib
import re
import shutil
import subprocess as sp
import sys

OUT = pathlib.Path('port/generated')
# GBA functions that game code declares as data, so they get absolute symbols too.
FUNCTIONS_USED_AS_DATA = {'SoundMainRAM'}
# Asm functions that no game code names, but that ROM data points to (m4a's
# sMPlayJumpTableTemplate). They need dispatch entries, so they get stubs too.
REACHED_THROUGH_ROM_DATA = {
    'SoundMainBTM', 'RealClearChain', 'ply_fine', 'ply_goto', 'ply_patt', 'ply_pend', 'ply_rept',
    'ply_prio', 'ply_tempo', 'ply_keysh', 'ply_voice', 'ply_vol', 'ply_pan', 'ply_bend',
    'ply_bendr', 'ply_lfodl', 'ply_modt', 'ply_tune', 'ply_port',
}
# GBA library functions that the PC runtime supplies.
NATIVE_RUNTIME = {'memcpy', 'memset', '__divsi3', '__modsi3', '__udivsi3', '__umodsi3'}
VALID_NAME = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')
HEADER = '// Generated by port/tools/gen_symbols.py from the GBA symbol table. Do not edit.\n'


def nm(tool, *args):
    return sp.run([tool, *args], capture_output=True, text=True, check=True).stdout.splitlines()


def elf_symbols(tool, elf):
    """Return {name: (address, type)}; a local name defined at several addresses maps to None."""
    seen = {}
    for line in nm(tool, '-n', elf):
        parts = line.split()
        if len(parts) == 3 and VALID_NAME.match(parts[2]):
            seen.setdefault(parts[2], set()).add((int(parts[0], 16), parts[1]))
    syms = {}
    for name, defs in seen.items():
        globals_ = [d for d in defs if d[1].isupper()]
        if len(globals_) == 1:
            syms[name] = globals_[0]
        elif len(defs) == 1:
            syms[name] = next(iter(defs))
        else:
            syms[name] = None
    return syms


def lib_symbols(tool, lib):
    defined, undefined = {}, set()
    for line in nm(tool, lib):
        parts = line.split()
        if len(parts) == 2 and parts[0] == 'U':
            undefined.add(parts[1])
        elif len(parts) == 3:
            defined[parts[2]] = parts[1]
    return defined, undefined - set(defined)


STATIC_DEFINITION = re.compile(r'^static\s+(?:inline\s+)?[^;=(]*?\b([A-Za-z_]\w*)\s*\([^;{]*\)\s*\{', re.M)


def c_static_functions():
    """Return {name: source} for the static functions defined in the game sources."""
    found = {}
    for path in sorted(pathlib.Path('src').rglob('*.c')):
        for m in STATIC_DEFINITION.finditer(path.read_text(errors='replace')):
            found.setdefault(m.group(1), path.as_posix())
    return found


def is_function(kind):
    return kind in 'Tt'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--elf', required=True)
    ap.add_argument('--lib', required=True)
    ap.add_argument('--nm', default=shutil.which('llvm-nm') or 'llvm-nm')
    args = ap.parse_args()

    elf = elf_symbols(args.nm, args.elf)
    defined, unresolved = lib_symbols(args.nm, args.lib)
    errors = []

    # Data: every global ELF data symbol that the PC build does not define itself, and
    # each local one that game code refers to.
    data = {}
    for name, sym in elf.items():
        if sym is None or name in defined:
            continue
        addr, kind = sym
        wanted = (not is_function(kind) and (kind.isupper() or name in unresolved)) or \
                 (name in FUNCTIONS_USED_AS_DATA)
        if wanted:
            data[name] = addr
    ambiguous = sorted(n for n in unresolved if n in elf and elf[n] is None)
    errors += ['%s is defined more than once in the ELF' % n for n in ambiguous]

    # Functions: native ones go in the dispatch table, missing ones get stubs.
    functions = sorted((addr, name) for name, (addr, kind) in ((n, s) for n, s in elf.items() if s)
                       if is_function(kind) and defined.get(name) == 'T')
    stubs = sorted((set(unresolved) | REACHED_THROUGH_ROM_DATA) - set(defined) - NATIVE_RUNTIME - FUNCTIONS_USED_AS_DATA)
    stubs = [n for n in stubs if n in elf and elf[n] and is_function(elf[n][1])]
    # The stubs dispatch too: game code stores pointers to asm functions in GBA memory.
    functions = sorted(functions + [(elf[n][0], n) for n in stubs])
    missing = sorted(n for n in unresolved if n not in elf and n not in NATIVE_RUNTIME)
    # Local code symbols are asm labels unless a game source defines a static function of that
    # name. A static function has no native symbol, so a GBA pointer to it could not dispatch.
    static_functions = c_static_functions()
    local_functions = sorted(n for n, s in elf.items() if s and s[1] == 't' and n in static_functions)

    if errors:
        sys.exit('\n'.join(errors))
    OUT.mkdir(parents=True, exist_ok=True)

    lines = [HEADER.replace('//', '#'), '# Absolute symbols at GBA addresses for the game\'s data.\n']
    for name in sorted(data, key=lambda n: (data[n], n)):
        lines.append('    .globl %s\n    .set %s, 0x%08X\n' % (name, name, data[name]))
    (OUT / 'gba_symbols.s').write_bytes(''.join(lines).encode())

    lines = [HEADER, '#include "port/gba_functions.h"\n\n']
    lines += ['void %s(void);\n' % name for _, name in functions]
    lines.append('\n// Sorted by address for PortLookupGbaFunction().\n')
    lines.append('const struct GbaFunction gGbaFunctions[] = {\n')
    lines += ['    { 0x%08X, (PortFunc)%s, "%s" },\n' % (addr & ~1, name, name) for addr, name in functions]
    lines.append('};\n\nconst unsigned int gGbaFunctionCount = sizeof(gGbaFunctions) / sizeof(gGbaFunctions[0]);\n')
    (OUT / 'gba_functions.c').write_bytes(''.join(lines).encode())

    lines = [HEADER, '// The GBA functions below have no native version yet. A platform definition\n',
             '// of the same name replaces the weak stub.\n', '#include "port/gba_functions.h"\n\n']
    for name in stubs:
        lines.append('__attribute__((weak)) void %s(void) { PortMissingFunction("%s", 0x%08X); }\n'
                     % (name, name, elf[name][0]))
    (OUT / 'gba_stubs.c').write_bytes(''.join(lines).encode())

    print('%d data symbols, %d functions in the dispatch table (%d of them stubs)'
          % (len(data), len(functions), len(stubs)))
    print('stubs: ' + ' '.join(stubs))
    if local_functions:
        print('static functions in the ELF, not dispatchable (make them non-static under PORTABLE): '
              + ' '.join('%s (%s)' % (n, static_functions[n]) for n in local_functions))
    if missing:
        print('referenced but not in the ELF (the platform must define them): ' + ' '.join(missing))


if __name__ == '__main__':
    main()
