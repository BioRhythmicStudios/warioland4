#ifndef GUARD_PORT_BIOS_H
#define GUARD_PORT_BIOS_H

#include <stdint.h>

// The GBA BIOS functions the game uses, run natively. Game code reaches them through
// SYSCALL(), which calls PlatformSyscall(), and through the asm wrappers in asm/syscalls.s
// (CPUSet, LZ77UnCompVram), whose weak stubs these definitions replace. They follow the
// hardware, including its quirks, so that GBA memory ends up as it would on the GBA.

// BIOS call 0x0B: copies or fills `control & 0x1FFFFF` halfwords, or words if bit 26 is set.
// Bit 24 keeps the source fixed (a fill). Addresses are aligned down to the unit size.
void CPUSet(const void *src, void *dest, uint32_t control);

// BIOS call 0x12: LZ77 decompression with halfword writes, for VRAM. Like the hardware it
// reads earlier output back from the destination, so a back-reference at distance 1 from an
// odd position reads the byte that was there before (GBATEK: "disp=0 is not supported").
void LZ77UnCompVram(const uint32_t *src, void *dest);

// SYSCALL(n) on the PC. Halt yields from the game coroutine until the frame loop
// (port/include/port/frame.h) requests an interrupt. Other calls are reported and stop the game.
void PlatformSyscall(int num);

// For --test-bios: the LZ77 streams the game passes to LZ77UnCompVram, by GBA address.
// Generated by port/tools/gen_lz77_sources.py.
struct PortLz77Source {
    const char *name;
    uint32_t gbaAddress;
};
extern const struct PortLz77Source gLz77Sources[];
extern const unsigned int gLz77SourceCount;

// Runs the BIOS unit tests. The ROM must be loaded. Returns nonzero on failure.
int PortBiosTest(void);

#endif  // GUARD_PORT_BIOS_H
